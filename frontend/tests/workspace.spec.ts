test('responsive layout, settings and task controls', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  for (const viewport of [{width: 1366, height: 768}, {width: 1024, height: 768}, {width: 683, height: 512}, {width: 375, height: 812}]) {
    await page.setViewportSize(viewport)
    await expect(page.getByRole('button', {name: '开始生成'})).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.setViewportSize({width: 1366, height: 768})
  await page.locator('html').evaluate(element => { element.style.zoom = '1.5' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.locator('html').evaluate(element => { element.style.zoom = '' })
  await page.getByLabel('输出格式', {exact: true}).selectOption('word')
  await expect(page.getByLabel('PDF 排版引擎')).toHaveCount(0)
  await page.getByRole('button', {name: '题目练习', exact: true}).click()
  await expect(page.getByRole('button', {name: '真题来源 · 第 1–17 届'})).toBeVisible()
  await expect(page.getByLabel('学习模块').locator('option[value="all"]')).toHaveText('全部模块（一键生成 7 份）')
  await page.getByRole('button', {name: '设置', exact: true}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('AI 服务', {exact:true}).selectOption('DeepSeek (DSH)')
  await expect(page.getByLabel('运行方式')).toHaveValue('API')
  await page.getByLabel('API 密钥', {exact:false}).fill('browser-test-secret')
  await page.getByLabel('API 模型 ID').fill('manual-model')
  await page.getByRole('button', {name:'完成设置'}).click()
  await page.reload()
  await page.getByRole('button', {name:'设置', exact:true}).click()
  await expect(page.getByLabel('API 密钥', {exact:false})).toHaveValue('')
  await expect(page.getByText('已配置', {exact:true})).toBeVisible()
  await expect(page.getByLabel('API 模型 ID')).toHaveValue('manual-model')
  const stored = await page.evaluate(() => JSON.stringify(localStorage))
  expect(stored).not.toContain('browser-test-secret')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(errors).toEqual([])
})

test('generation survives reload and multiple tabs, results open', async ({ page, context }) => {
  await page.getByRole('button', {name:'开始生成', exact:true}).click()
  await expect(page.getByRole('button', {name:'任务执行中'})).toBeDisabled()
  await expect(page.getByLabel('科目', {exact:true})).toBeDisabled()
  const second = await context.newPage()
  await second.goto('/')
  await expect(second.getByRole('button', {name:'任务执行中'})).toBeDisabled()
  const current = await page.request.get('/api/jobs/current')
  const job = await current.json()
  await page.reload()
  await expect(page.getByRole('button', {name:'打开文件', exact:true})).toBeVisible()
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '100')
  await expect.poll(async () => (await (await page.request.get('/api/jobs/current')).json()).id).toBe(job.id)
  await page.getByRole('button', {name:'打开文件', exact:true}).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await second.close()
})

test('subjects switch modules, counts and real generation', async ({ page }) => {
  const subject = page.getByLabel('科目', {exact:true})
  const chapter = page.getByLabel('学习模块')
  await chapter.selectOption('模块三：一元积分学')
  await subject.selectOption('复变函数')
  await expect(chapter).toBeEnabled()
  await expect(chapter.locator('option')).toHaveCount(9)
  await expect(chapter.locator('option[value="all"]')).toHaveText('全部模块（一键生成 7 份）')
  await chapter.selectOption('模块七：拉普拉斯之变换')
  await page.getByRole('button', {name:'题目练习', exact:true}).click()
  await expect(page.getByRole('button', {name:'真题来源 · 第 1–17 届'})).toHaveCount(0)
  await page.reload()
  await expect(subject).toHaveValue('复变函数')
  await expect(chapter).toHaveValue('模块七：拉普拉斯之变换')
  const request = page.waitForRequest(request => request.url().endsWith('/api/jobs') && request.method() === 'POST')
  await page.getByRole('button', {name:'开始生成', exact:true}).click()
  expect((await request).postDataJSON().settings.chapter).toBe('模块七：拉普拉斯之变换')
  await expect(page.getByRole('button', {name:'开始生成', exact:true})).toBeEnabled()
  await subject.selectOption('数学竞赛')
  await expect(chapter).toHaveValue('模块三：一元积分学')
  await expect(page.getByRole('button', {name:'真题来源 · 第 1–17 届'})).toBeVisible()
  const setup = page.getByRole('button', {name:'一键配置环境', exact:true})
  const generate = page.getByRole('button', {name:'开始生成', exact:true})
  expect((await setup.boundingBox())!.y).toBeLessThan((await generate.boundingBox())!.y)
})

test('late model query cannot replace current provider list', async ({ page }) => {
  await page.getByRole('button', {name:'设置', exact:true}).click()
  await page.getByLabel('运行方式').selectOption('API')
  await page.getByLabel('API 密钥', {exact:false}).fill('browser-test-secret')
  let finish: () => void = () => {}
  const gate = new Promise<void>(resolve => { finish = resolve })
  await page.route('**/api/models', async route => { await gate; await route.fulfill({json:{models:['stale-model']}}) })
  await page.getByRole('button', {name:'读取模型', exact:true}).click()
  await page.getByLabel('AI 服务', {exact:true}).selectOption('豆包')
  const response = page.waitForResponse("**/api/models")
  finish()
  await response
  await expect(page.getByLabel('模型 / 推理接入点 ID')).toBeVisible()
  await expect(page.locator('datalist option[value="stale-model"]')).toHaveCount(0)
})

